"""Create deterministic, original fictional demo images and ticket PDF."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT=Path(__file__).resolve().parents[1]/"examples/fictional-trip"
def font(size,bold=False):
    names=["C:/Windows/Fonts/arialbd.ttf" if bold else "C:/Windows/Fonts/arial.ttf","DejaVuSans-Bold.ttf" if bold else "DejaVuSans.ttf"]
    for name in names:
        try:return ImageFont.truetype(name,size)
        except OSError:pass
    return ImageFont.load_default()
def scene(name,title,subtitle,colors,mode):
    image=Image.new("RGB",(1400,900),colors[0]);d=ImageDraw.Draw(image)
    d.rectangle((0,520,1400,900),fill=colors[1]);d.ellipse((1000,80,1190,270),fill="#f8ce70")
    if mode=="harbor":
        d.rectangle((0,650,1400,900),fill="#357a87");
        for i,c in enumerate(["#d1495b","#edae49","#2a9d8f","#775da6","#f08a5d"]):d.rectangle((100+i*180,380-(i%2)*60,250+i*180,680),fill=c);d.polygon((720,650,1050,650,880,480),fill="#f8f4e3")
    elif mode=="museum":
        d.rectangle((160,330,1240,740),fill="#e9e1d0");d.polygon((100,330,1300,330,700,130),fill="#f6ead2");
        for x in range(230,1210,160):d.rectangle((x,350,x+55,740),fill="#7d8471")
    else:
        for x in range(120,1350,210):d.ellipse((x,350,x+120,700),fill="#557c55");d.rectangle((x+50,630,x+70,800),fill="#694c3d")
        d.polygon((50,850,650,520,1380,850),fill="#d8c39d")
    d.rounded_rectangle((70,65,930,250),radius=24,fill="#fffaf2dd");d.text((105,90),title,font=font(58,True),fill="#28312e");d.text((108,175),subtitle,font=font(27),fill="#52605b")
    image.save(ROOT/"media"/name,quality=90)
def ticket():
    pages=[]
    for no,(title,color) in enumerate([("Outbound harbor ferry","#146c63"),("Return harbor ferry","#275d7a")],1):
        im=Image.new("RGB",(1240,1754),"white");d=ImageDraw.Draw(im);d.rectangle((0,0,1240,260),fill=color);d.text((90,70),"DEMO TICKET",font=font(68,True),fill="white");d.text((90,320),title,font=font(52,True),fill="#222");d.text((90,420),"Fictional sample — not valid for travel",font=font(32),fill="#b33b35");d.text((90,540),f"Document page {no} of 2",font=font(30),fill="#444");d.text((90,620),"Travelers: Alex Demo · Sam Demo",font=font(30),fill="#444");d.text((90,700),"Event: North Harbor",font=font(30),fill="#444");d.rectangle((90,850,1150,1180),outline=color,width=10);d.text((225,970),"NOT A REAL QR CODE",font=font(48,True),fill=color);d.text((90,1440),"Generated by the open-source fictional demo.",font=font(26),fill="#666");pages.append(im)
    pages[0].save(ROOT/"tickets/fictional-ferry.pdf",save_all=True,append_images=pages[1:],resolution=150)
def main():
    (ROOT/"media").mkdir(parents=True,exist_ok=True);(ROOT/"tickets").mkdir(parents=True,exist_ok=True)
    scene("cover.jpg","Harbor & Old Town","A fictional two-day pocket journey",("#bfd6ce","#d7c89e"),"harbor")
    scene("day-1.jpg","Day 1 · Set sail","Harbor walks and a sunset ferry",("#aad0cf","#dbc78e"),"harbor")
    scene("day-2.jpg","Day 2 · Look closer","Museum rooms and garden paths",("#c9d7be","#d9c5a3"),"museum")
    scene("north-harbor.jpg","North Harbor","Original fictional illustration",("#b8d8d6","#d8c08d"),"harbor")
    scene("civic-museum.jpg","Civic Museum","Original fictional illustration",("#d8d1bf","#bba988"),"museum")
    scene("lantern-garden.jpg","Lantern Garden","Original fictional illustration",("#c0d5b7","#bca882"),"garden")
    ticket()
if __name__=="__main__":main()
